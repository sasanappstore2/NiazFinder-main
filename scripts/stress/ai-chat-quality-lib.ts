/** Shared quality flags for platform AI chat answers. */

export type QualityFlag =
  | 'empty'
  | 'unavailable_msg'
  | 'hallucinated_topic'
  | 'leaked_tool_json'
  | 'too_short'
  | 'too_long'
  | 'vague_howto'
  | 'overlong_for_smalltalk'
  | 'no_concrete_category'
  | 'no_account_facts'
  | 'english_thinking'
  | 'boilerplate'
  | 'no_spaces_glued'
  | 'wrong_wallet_story';

export function scoreAgentAnswer(input: {
  user: string;
  answer: string;
  thinking?: string;
}): { flags: QualityFlag[]; score: number } {
  const flags: QualityFlag[] = [];
  const a = input.answer.trim();
  const u = input.user.trim();
  const thinking = (input.thinking ?? '').trim();

  if (!a) flags.push('empty');
  if (a.includes('سرویس هوش مصنوعی موقتاً')) flags.push('unavailable_msg');
  if (/playstation|ps5|پلی.?استیشن/i.test(a) && !/playstation|ps5|پلی.?استیشن/i.test(u)) {
    flags.push('hallucinated_topic');
  }
  if (/\{"action"|<\|?\s*tool_call|call\s*:\s*[a-z_]|get_site_categories\{|search_needs_agent/i.test(a)) {
    flags.push('leaked_tool_json');
  }
  if (a.length < 20 && !/^(سلام|ممنون|خواهش|مرسی)/.test(u)) flags.push('too_short');
  if (a.length > 650) flags.push('too_long');

  if (
    /چطور|راهنما|ثبت/.test(u) &&
    /داشبورد|ثبت نیاز/.test(a) &&
    !/\/post|نیازفایندر|دکمه|از منو|مسیر|صفحه/.test(a)
  ) {
    flags.push('vague_howto');
  }

  if (/^(سلام|سلام، خوبی\؟|ممنون|مرسی)/.test(u) && a.length > 220) {
    flags.push('overlong_for_smalltalk');
  }

  if (
    /دسته|کتگوری|خودرو|املاک/.test(u) &&
    !/املاک|خودرو|موبایل|لوازم|خدمات|استخدام|دیجیتال|خانه|آپارتمان|کالا|ورزش|پوشاک|وسایل|نقلیه|slug|دسته/.test(
      a,
    )
  ) {
    flags.push('no_concrete_category');
  }

  if (/وضعیت حساب|کیف پول|موجودی/.test(u) && !/\d|تومان|موجودی|نقش|تأیید|تایید|شارژ|میلیون/.test(a)) {
    flags.push('no_account_facts');
  }

  if (/Thinking Process|I need to|Let me think/i.test(thinking)) flags.push('english_thinking');
  if (/خوشحال می‌شوم|در خدمتم|چطور می‌توانم امروز/.test(a)) flags.push('boilerplate');

  // Glued Persian (almost no spaces in a long string)
  const spaceRatio = (a.match(/\s/g) ?? []).length / Math.max(a.length, 1);
  if (a.length > 40 && spaceRatio < 0.04) flags.push('no_spaces_glued');

  if (
    /کیف\s*پول|موجودی/.test(u) &&
    /از کیف پول شما هزینه کسر|پیام.*کسب.?وکار.*کیف پول شما/i.test(a)
  ) {
    flags.push('wrong_wallet_story');
  }

  const score = Math.max(0, 100 - flags.length * 18);
  return { flags, score };
}

